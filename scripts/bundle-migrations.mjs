/* global console, process */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const migrationsDir = join(root, "supabase", "migrations");
const outputPath = join(root, "supabase", "zigo-full-migrations.sql");

function getExpectedMigrations() {
  if (!existsSync(migrationsDir)) return [];
  const files = readdirSync(migrationsDir).filter((name) => name.endsWith(".sql")).sort();
  return files;
}

const expected = getExpectedMigrations();
const REQUIRED_CHECKPOINTS = [
  "001_initial_schema.sql",
  "055_demo_social_interactions_reset.sql",
  "066_ad_state_and_premium_system.sql",
  "077_moderation_report_resolved_at.sql",
  "078_admin_billing_grants.sql",
  "079_update_own_account_kind.sql",
];

function main() {
  if (!existsSync(migrationsDir)) {
    throw new Error("Missing supabase/migrations directory");
  }

  const missing = REQUIRED_CHECKPOINTS.filter((name) => !expected.includes(name));
  if (missing.length > 0) {
    throw new Error(`Missing critical migration checkpoints: ${missing.join(", ")}`);
  }

  const chunks = [
    "-- Zigo full migration bundle",
    "-- Generated by npm run migrations:bundle",
    "-- Paste into Supabase SQL Editor as one run, or apply files individually in order.",
    "",
  ];

  for (const fileName of expected) {
    const filePath = join(migrationsDir, fileName);
    const sql = readFileSync(filePath, "utf8").trim();
    chunks.push(`-- >>> ${fileName}`);
    chunks.push(sql);
    chunks.push("");
  }

  writeFileSync(outputPath, `${chunks.join("\n")}\n`, "utf8");

  console.log(`PASS Bundled ${expected.length} migrations`);
  console.log(`Output: ${outputPath}`);
}

main();
